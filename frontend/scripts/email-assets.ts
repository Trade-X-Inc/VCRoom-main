// Builds the email files. Run with: node scripts/build-email-assets.mjs [supabase] [preview]
//   supabase  writes supabase/email-templates/*.html and README.md (the owner pastes these in the Supabase dashboard)
//   preview   writes frontend/email-preview/ (git-ignored): every app email (.html and .txt), every Supabase template
//             with sample values filled in, and index.html to browse them. It never sends anything.
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  SUPABASE_TEMPLATES,
  renderSupabaseTemplate,
} from "../src/lib/email/supabase-templates";
import { APP_SAMPLES, fillSample } from "../src/lib/email/email-samples";

const root = resolve(import.meta.dirname ?? ".", "..");
const repo = resolve(root, "..");
const write = (path: string, body: string) => {
  mkdirSync(resolve(path, ".."), { recursive: true });
  writeFileSync(path, body);
};

const args = process.argv.slice(2);

if (args.includes("supabase")) {
  const dir = resolve(repo, "supabase/email-templates");
  for (const t of SUPABASE_TEMPLATES)
    write(resolve(dir, t.file), renderSupabaseTemplate(t));
  const rows = SUPABASE_TEMPLATES.map(
    (t) => `| ${t.dashboardName} | \`${t.file}\` | ${t.model.subject} |`,
  ).join("\n");
  write(
    resolve(dir, "README.md"),
    `# Supabase email templates

Generated by \`node frontend/scripts/build-email-assets.mjs supabase\`. Do not edit the HTML by hand: change
\`frontend/src/lib/email/supabase-templates.ts\` and run the script again.

These files change nothing by themselves. The project owner pastes them into the Supabase dashboard.

## How to paste them (simple steps)

1. Open the Supabase dashboard and choose the Lengdon project.
2. Go to **Authentication**, then **Emails** (the email templates page).
3. Open one template from the table below.
4. Copy the **subject** from the table into the Subject box.
5. Open the matching file, copy **all** of it, and paste it into the message box. Replace what is there.
6. Save. Repeat for each row.
7. Send yourself a test from the dashboard if you want to check it.

| Template name in the dashboard | File | Subject to paste |
|---|---|---|
${rows}

## Good to know

- Supabase templates are HTML only. There is no plain-text box, so these emails have no plain-text part.
- The words **{{ .Something }}** are Supabase variables. Leave them exactly as they are.
- The reset-password and magic-link emails say "This link expires in 15 minutes". That matches the Supabase setting
  *Email OTP expiration* = 900 seconds. If you change that setting, tell the developer so the text can change too.
- The footer has a hidden note for the owner: the postal address or legal-entity line is **not** filled in. See the
  "Owner placeholders" section of CLAUDE.md §20.27.
- Emails use no images, no remote fonts and no tracking.
`,
  );
  console.log(
    `wrote ${SUPABASE_TEMPLATES.length} templates + README to supabase/email-templates/`,
  );
}

if (args.includes("preview")) {
  const dir = resolve(root, "email-preview");
  const items: string[] = [];
  for (const s of APP_SAMPLES) {
    write(resolve(dir, `app-${s.id}.html`), s.mail.html);
    write(resolve(dir, `app-${s.id}.txt`), s.mail.text);
    items.push(
      `<tr><td>App</td><td>${s.id}</td><td>${s.mail.subject.replace(/</g, "&lt;")}</td><td>${s.to}</td><td><a href="app-${s.id}.html">HTML</a> · <a href="app-${s.id}.txt">text</a></td></tr>`,
    );
  }
  for (const t of SUPABASE_TEMPLATES) {
    write(
      resolve(dir, `supabase-${t.file}`),
      fillSample(renderSupabaseTemplate(t)),
    );
    items.push(
      `<tr><td>Supabase</td><td>${t.id}</td><td>${t.model.subject}</td><td>Supabase Auth</td><td><a href="supabase-${t.file}">HTML</a></td></tr>`,
    );
  }
  write(
    resolve(dir, "index.html"),
    `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Email preview</title></head><body style="font-family:Arial,sans-serif;margin:24px"><h1>Lengdon email preview</h1><p>Sample data only. Nothing here is sent.</p><table border="1" cellpadding="8" cellspacing="0"><tr><th>Kind</th><th>Email</th><th>Subject</th><th>Who may receive it</th><th>Open</th></tr>${items.join("")}</table></body></html>`,
  );
  console.log(
    `wrote ${APP_SAMPLES.length + SUPABASE_TEMPLATES.length} previews to frontend/email-preview/ (open index.html)`,
  );
}
